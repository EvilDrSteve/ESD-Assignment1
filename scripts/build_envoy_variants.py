"""Write the Envoy configs for the Part D experiments from envoy/envoy.yaml.

Each variant is the base config (round robin, A:B:C = 1:1:1) with only the
lines the experiment changes, so the variants never drift from the base.
Edit envoy/envoy.yaml, then re-run this script.

    python scripts/build_envoy_variants.py

Use a variant (Compose mounts envoy/$ENVOY_CONFIG, default envoy.yaml):

    ENVOY_CONFIG=weighted-2-1-1.yaml docker compose up -d --force-recreate envoy
    docker compose up -d --force-recreate envoy        # back to the base config
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENVOY = os.path.join(ROOT, "envoy")


def replace(text: str, old: str, new: str, count: int) -> str:
    """Replace exactly `count` occurrences, so a base-config edit can't silently break a variant."""
    found = text.count(old)
    if found != count:
        raise SystemExit(f"expected {count} x {old!r} in envoy.yaml, found {found}")
    return text.replace(old, new)


def weight(text: str, replica: str, w: int) -> str:
    """Set one replica's load_balancing_weight in both clusters."""
    for port in ("8050", "50051"):
        endpoint = f"{{ hostname: {replica}, address: {{ socket_address: {{ address: assignment-1-app-"
        lines = text.split("\n")
        hits = [i for i, l in enumerate(lines) if endpoint in l and f"port_value: {port} }}" in l]
        if len(hits) != 1 or "load_balancing_weight" not in lines[hits[0] + 1]:
            raise SystemExit(f"endpoint {replica}:{port} not found as expected")
        indent = lines[hits[0] + 1].split("load")[0]
        lines[hits[0] + 1] = f"{indent}load_balancing_weight: {w}"
        text = "\n".join(lines)
    return text


def after_lb_policy(text: str, cluster: str, block: str) -> str:
    """Insert `block` right after the lb_policy line of one cluster."""
    lines = text.split("\n")
    start = lines.index(f"    - name: {cluster}")
    at = next(i for i in range(start, len(lines)) if lines[i].strip().startswith("lb_policy:"))
    return "\n".join(lines[:at + 1] + block.rstrip("\n").split("\n") + lines[at + 1:])


# Active health checks (#15). Envoy's main thread probes every host; a host
# is removed after `unhealthy_threshold` failed probes in a row and returns
# after `healthy_threshold` passed ones. Worst-case removal after a crash is
# about interval * unhealthy_threshold (+ timeout); recovery after the
# replica is ready is about interval * healthy_threshold.
HC_TIMING = """      health_checks:
        - timeout: 1s
          interval: 2s
          unhealthy_threshold: 2
          healthy_threshold: 2
          no_traffic_interval: 2s       # same pace even before traffic arrives
          event_log_path: /var/log/envoy/health.log"""
HC_HTTP = HC_TIMING + """
          http_health_check: { path: /health }"""
HC_GRPC = HC_TIMING + """
          grpc_health_check: { service_name: "" }   # grpc.health.v1, overall server status"""


def header(text: str, title: str) -> str:
    return (f"# GENERATED by scripts/build_envoy_variants.py from envoy.yaml; do not edit.\n"
            f"# Variant: {title}\n#\n") + text


VARIANTS = {
    # #13: A gets twice the share of B and C (expected 50 / 25 / 25 %)
    "weighted-2-1-1.yaml": lambda t: header(weight(t, "A", 2), "weighted round robin, A:B:C = 2:1:1"),
    # #14: equal weights, LEAST_REQUEST. With equal weights Envoy samples two
    # random hosts per request and takes the one with fewer active requests
    # (power of two choices, default choice_count 2).
    "least-request.yaml": lambda t: header(
        replace(t, "lb_policy: ROUND_ROBIN", "lb_policy: LEAST_REQUEST", 2),
        "least request (power of two choices), equal weights"),
    # #15: round robin 1:1:1 plus active health checks on both clusters
    "health-checks.yaml": lambda t: header(
        after_lb_policy(after_lb_policy(t, "store_http", HC_HTTP), "store_grpc", HC_GRPC),
        "round robin, equal weights, active health checks (HTTP /health, gRPC grpc.health.v1)"),
}


def main():
    with open(os.path.join(ENVOY, "envoy.yaml")) as f:
        base = f.read()
    for name, build in VARIANTS.items():
        with open(os.path.join(ENVOY, name), "w") as f:
            f.write(build(base))
        print("wrote", os.path.join("envoy", name))


if __name__ == "__main__":
    main()
